use crate::application::think_service::{execute_thought_loop, run_single_turn, ThoughtPhase};
use crate::infrastructure::llm::inference::response_payload::extract_balanced_json;
use crate::infrastructure::patch::{clean_code_fence, FileObject, PatchObj};
use crate::UnevenConfig;
use anyhow::Result;
use serde::{Deserialize, Serialize};
use std::path::Path;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct SubtaskSpec {
    pub index: usize,
    pub title: String,
    pub instructions: String,
    #[serde(default)]
    pub target_files: Vec<String>,
    #[serde(default = "default_max_files")]
    pub max_files: usize,
}

fn default_max_files() -> usize {
    3
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PlanPayload {
    pub strategy: String,
    pub subtasks: Vec<SubtaskSpec>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum SupervisorEvent {
    PlanningStarted,
    PlanCreated {
        total_subtasks: usize,
        strategy: String,
        subtasks: Vec<SubtaskSpec>,
    },
    SubagentStarted {
        subagent_idx: usize,
        total: usize,
        title: String,
        target_files: Vec<String>,
    },
    SubagentPhase {
        subagent_idx: usize,
        phase: ThoughtPhase,
    },
    SubagentCompleted {
        subagent_idx: usize,
        patches_generated: usize,
        summary: String,
    },
    EvaluatingSubagent {
        subagent_idx: usize,
    },
    AllCompleted {
        final_summary: String,
        file_object: Option<FileObject>,
    },
    Failed {
        subagent_idx: Option<usize>,
        reason: String,
    },
}

#[derive(Debug, Clone, PartialEq)]
pub struct MultiAgentResult {
    pub strategy: String,
    pub completed_subtasks: usize,
    pub subagent_reports: Vec<(String, String)>,
    pub file_object: Option<FileObject>,
}

const PRIME_PLANNER_SYSTEM: &str = r#"You are the Prime Supervisor & Lead Software Architect of Uneven.
Your responsibility is to analyze the user's software engineering task and decompose it into a sequential, dependency-ordered plan of 1 to 5 atomic subtasks.

Rules:
1. Deconstruct the task into logical sequential phases (e.g. interfaces/data models first, core business logic/services second, controllers/routes third).
2. Each subtask MUST specify target_files with a strict limit of 1 to 3 files to create or modify.
3. Subtasks must be focused, atomic, and independent or ordered by dependency.
4. HOST RESOURCE SAFETY: Strictly avoid parallel, multiple or redundant build/check commands (e.g. `cargo check`, `npm run build`, `pytest`) to prevent freezing the host PC. Rely on surgical static inspection.
5. Output STRICTLY a valid JSON object matching the schema below without markdown formatting or conversational text:
{
  "strategy": "Concise summary of architecture and execution strategy",
  "subtasks": [
    {
      "index": 1,
      "title": "Define User Model and Repository Interface",
      "instructions": "Create src/domain/user.rs with User struct and trait definition.",
      "target_files": ["src/domain/user.rs"],
      "max_files": 2
    }
  ]
}
"#;

/// Parses JSON planning payload generated by the Prime Supervisor.
fn parse_plan_payload(raw: &str) -> Option<PlanPayload> {
    let cleaned = clean_code_fence(raw);
    if let Ok(plan) = serde_json::from_str::<PlanPayload>(&cleaned) {
        return Some(plan);
    }
    if let Some(json_slice) = extract_balanced_json(&cleaned)
        && let Ok(plan) = serde_json::from_str::<PlanPayload>(&json_slice) {
            return Some(plan);
        }
    None
}

/// Executes a hierarchical multi-agent supervisor workflow:
/// 1. Prime decomposes high-level goal into sequential atomic subtasks.
/// 2. For each subtask, calls `execute_thought_loop` (Actor-Critic think engine).
/// 3. Prime dynamically evaluates progress, updates accumulated workspace context, and delegates to the next subagent.
/// 4. Aggregates all synthesized patches into a consolidated `FileObject`.
pub async fn execute_multi_agent_workflow<F>(
    goal: &str,
    initial_files: &[String],
    config: &UnevenConfig,
    root: &Path,
    provider_opt: Option<&str>,
    model_opt: Option<&str>,
    mut event_callback: Option<F>,
) -> Result<MultiAgentResult>
where
    F: FnMut(SupervisorEvent) + Send + Sync,
{
    if let Some(ref mut cb) = event_callback {
        cb(SupervisorEvent::PlanningStarted);
    }

    // 1. Prime Planning Phase
    let mut prime_brain = config.get_brain_for_command("think");
    if prime_brain.provider.is_empty() || prime_brain.provider == "default" {
        prime_brain = config.get_brain_for_command("ask");
    }
    if let Some(p) = provider_opt {
        prime_brain.provider = p.to_string();
    }
    if let Some(m) = model_opt {
        prime_brain.model = m.to_string();
    }

    let threads = prime_brain
        .local
        .as_ref()
        .and_then(|l| l.threads)
        .unwrap_or(4);
    let max_context = if prime_brain.provider == "local" {
        4096
    } else {
        1000000
    };

    let planning_prompt = format!(
        "Task to plan:\n{}\n\nAttached reference files:\n{}",
        goal,
        if initial_files.is_empty() {
            "(None)".to_string()
        } else {
            initial_files.join(", ")
        }
    );

    let raw_plan = run_single_turn(
        &planning_prompt,
        PRIME_PLANNER_SYSTEM,
        &prime_brain,
        threads,
        max_context,
    )
    .await
    .unwrap_or_default();

    let plan = parse_plan_payload(&raw_plan).unwrap_or_else(|| PlanPayload {
        strategy: "Direct execution plan".to_string(),
        subtasks: vec![SubtaskSpec {
            index: 1,
            title: "Execute Task".to_string(),
            instructions: goal.to_string(),
            target_files: initial_files.to_vec(),
            max_files: 3,
        }],
    });

    let total_subtasks = plan.subtasks.len();
    if let Some(ref mut cb) = event_callback {
        cb(SupervisorEvent::PlanCreated {
            total_subtasks,
            strategy: plan.strategy.clone(),
            subtasks: plan.subtasks.clone(),
        });
    }

    // 2. Sequential Subagent Execution
    let mut accumulated_files: Vec<String> = initial_files.to_vec();
    let mut aggregated_patches: Vec<PatchObj> = Vec::new();
    let mut subagent_reports: Vec<(String, String)> = Vec::new();

    for sub in &plan.subtasks {
        if let Some(ref mut cb) = event_callback {
            cb(SupervisorEvent::SubagentStarted {
                subagent_idx: sub.index,
                total: total_subtasks,
                title: sub.title.clone(),
                target_files: sub.target_files.clone(),
            });
        }

        // Subtask prompt with bounded scope and explicit target limits
        let sub_task_prompt = format!(
            "Subtask #{}/{} [{}]\n\nArchitectural Strategy: {}\n\nInstructions:\n{}\n\nStrict target files (max {}): {}\n\nPerform self-reflection and synthesize surgical patches exclusively for these files.",
            sub.index,
            total_subtasks,
            sub.title,
            plan.strategy,
            sub.instructions,
            sub.max_files,
            sub.target_files.join(", ")
        );

        // Combine accumulated created files with target files for progressive context
        let mut subagent_context_files = accumulated_files.clone();
        for tf in &sub.target_files {
            if !subagent_context_files.contains(tf) {
                subagent_context_files.push(tf.clone());
            }
        }

        let sub_idx = sub.index;
        let mut sub_cb = |phase: ThoughtPhase| {
            if let Some(ref mut cb) = event_callback {
                cb(SupervisorEvent::SubagentPhase {
                    subagent_idx: sub_idx,
                    phase,
                });
            }
        };

        let think_res = execute_thought_loop(
            &sub_task_prompt,
            &subagent_context_files,
            config,
            root,
            provider_opt,
            model_opt,
            Some(&mut sub_cb),
        )
        .await;

        match think_res {
            Ok(thought_result) => {
                let mut patches_count = 0;
                if let Some(file_obj) = thought_result.file_object {
                    for patch in file_obj.patch {
                        if !accumulated_files.contains(&patch.path) {
                            accumulated_files.push(patch.path.clone());
                        }
                        patches_count += 1;
                        aggregated_patches.push(patch);
                    }
                }

                if let Some(ref mut cb) = event_callback {
                    cb(SupervisorEvent::EvaluatingSubagent {
                        subagent_idx: sub.index,
                    });
                    cb(SupervisorEvent::SubagentCompleted {
                        subagent_idx: sub.index,
                        patches_generated: patches_count,
                        summary: thought_result.final_response.clone(),
                    });
                }

                subagent_reports.push((sub.title.clone(), thought_result.final_response));
            }
            Err(e) => {
                let err_msg = format!("Subagent #{} failed: {}", sub.index, e);
                if let Some(ref mut cb) = event_callback {
                    cb(SupervisorEvent::Failed {
                        subagent_idx: Some(sub.index),
                        reason: err_msg.clone(),
                    });
                }
                subagent_reports.push((sub.title.clone(), err_msg));
            }
        }
    }

    // 3. Consolidated Multi-Agent Outcome
    let file_object = if aggregated_patches.is_empty() {
        None
    } else {
        Some(FileObject {
            session_id: "multi-agent-session".to_string(),
            summary: Some(format!(
                "Consolidated mutations from {} subagents across {} files",
                plan.subtasks.len(),
                aggregated_patches.len()
            )),
            patch: aggregated_patches,
        })
    };

    let final_summary = format!(
        "Multi-Agent Supervisor completed {} subtask(s) based on strategy: {}",
        subagent_reports.len(),
        plan.strategy
    );

    if let Some(ref mut cb) = event_callback {
        cb(SupervisorEvent::AllCompleted {
            final_summary: final_summary.clone(),
            file_object: file_object.clone(),
        });
    }

    Ok(MultiAgentResult {
        strategy: plan.strategy,
        completed_subtasks: subagent_reports.len(),
        subagent_reports,
        file_object,
    })
}
