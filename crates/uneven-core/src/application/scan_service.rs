#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct DepVulnerability {
    pub name: String,
    pub severity: String,
    pub is_direct: bool,
    pub range: String,
    pub fix_available: serde_json::Value,
    pub via: Vec<serde_json::Value>,
}

#[derive(Debug, Deserialize)]
struct NpmAuditOutput {
    vulnerabilities: Option<HashMap<String, NpmAuditVuln>>,
}

#[derive(Debug, Deserialize)]
struct NpmAuditVuln {
    name: Option<String>,
    severity: Option<String>,
    #[serde(rename = "isDirect")]
    is_direct: Option<bool>,
    range: Option<String>,
    #[serde(rename = "fixAvailable")]
    fix_available: Option<serde_json::Value>,
    via: Option<Vec<serde_json::Value>>,
}

#[derive(Debug, Serialize, Deserialize, Clone, Default, PartialEq, Eq)]
pub struct ScanSummary {
    pub critical: usize,
    pub high: usize,
    pub medium: usize,
    pub low: usize,
    pub info: usize,
}

#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]
pub struct CategoryGroup {
    pub category: String,
    pub icon: String,
    pub title: String,
    pub findings: Vec<SecurityFinding>,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct ScanResult {
    pub findings: Vec<SecurityFinding>,
    pub vulnerabilities: Vec<DepVulnerability>,
    pub audit_skipped: bool,
    pub audit_error: Option<String>,
    pub files_scanned: usize,
    pub dependencies_scanned: usize,
    pub duration_ms: u128,
    pub risk_level: Severity,
    pub summary: ScanSummary,
    pub grouped_findings: Vec<CategoryGroup>,
}

impl ScanResult {
    /// Formats the scan result into an executive Markdown report.
    pub fn to_markdown_report(&self, project_root: &Path, target: &str) -> String {
        let project_name = project_root
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or("project");
        let date = chrono::Utc::now().to_rfc3339();
        let mut md = format!(
            "# Security Audit Report: {}\n\n- **Target Directory**: {}\n- **Generated At**: {}\n- **Risk Level**: `{:?}`\n\n---\n\n",
            project_name, target, date, self.risk_level
        );

        if self.findings.is_empty() && self.vulnerabilities.is_empty() {
            md.push_str("## ✓ No vulnerabilities or malicious threats detected.\n");
        } else {
            md.push_str("## Findings Summary\n\n");
            md.push_str(&format!(
                "- **Critical**: {}\n- **High**: {}\n- **Medium**: {}\n- **Low**: {}\n- **Info**: {}\n\n---\n\n## Code & Malware Findings\n\n",
                self.summary.critical, self.summary.high, self.summary.medium, self.summary.low, self.summary.info
            ));

            for f in &self.findings {
                let mut detail = format!(
                    "### [{:?}] {} in `{}`\n- **Description**: {}\n- **Recommendation**: {}\n",
                    f.severity,
                    f.finding_type,
                    f.file.clone().unwrap_or_else(|| "N/A".to_string()),
                    f.description,
                    f.recommendation
                );
                if let Some(ref note) = f.llm_note {
                    detail.push_str(&format!("- **AI Audit Note**: {}\n", note));
                }
                detail.push('\n');
                md.push_str(&detail);
            }

            if !self.vulnerabilities.is_empty() {
                md.push_str("## Dependency Vulnerabilities (CVEs)\n\n");
                for v in &self.vulnerabilities {
                    md.push_str(&format!(
                        "- **{}** (severity: `{}`): range `{}`\n",
                        v.name, v.severity, v.range
                    ));
                }
                md.push('\n');
            }
        }
        md
    }

    /// Formats the scan result into a standalone HTML report.
    pub fn to_html_report(&self, project_root: &Path, target: &str) -> String {
        let project_name = project_root
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or("project");
        let title = format!("Security Audit - {}", project_name);

        let mut content = format!(
            r#"<header>
    <div>
      <h1>Security Audit Report: {}</h1>
      <p>Target: {} | Risk: {:?}</p>
    </div>
    <div class="meta">
      <span class="badge">Generated by Uneven Snatchy Security Engine</span>
    </div>
  </header>
  <div class="container">
    <div class="card">
      <h2>Executive Summary</h2>
      <div class="stats">
        <div class="stat"><div class="value">{}</div><div class="label">Critical</div></div>
        <div class="stat"><div class="value">{}</div><div class="label">High</div></div>
        <div class="stat"><div class="value">{}</div><div class="label">Medium</div></div>
        <div class="stat"><div class="value">{}</div><div class="label">Low</div></div>
      </div>
    </div>
    <div class="card">
      <h2>Vulnerability & Malware Registry</h2>
      <div class="tbl-wrap">
        <table>
          <thead>
            <tr>
              <th>Severity</th>
              <th>Type</th>
              <th>Location</th>
              <th>Description</th>
              <th>Recommendation</th>
            </tr>
          </thead>
          <tbody>"#,
            project_name, target, self.risk_level,
            self.summary.critical, self.summary.high, self.summary.medium, self.summary.low
        );

        for f in &self.findings {
            let file_loc = if let Some(ref file) = f.file {
                if let Some(line) = f.line {
                    format!("{}:{}", file, line)
                } else {
                    file.clone()
                }
            } else {
                "N/A".to_string()
            };

            let desc = if let Some(ref note) = f.llm_note {
                format!(
                    "{}<br/><small style=\"color: #6a737d;\"><strong>AI Note:</strong> {}</small>",
                    f.description, note
                )
            } else {
                f.description.clone()
            };

            content.push_str(&format!(
                r#"<tr>
              <td><strong>{:?}</strong></td>
              <td>{}</td>
              <td><code>{}</code></td>
              <td>{}</td>
              <td>{}</td>
            </tr>"#,
                f.severity, f.finding_type, file_loc, desc, f.recommendation
            ));
        }

        content.push_str(
            r#"          </tbody>
        </table>
      </div>
    </div>
  </div>"#,
        );

        crate::infrastructure::reporting::generate_html_report(&title, &content)
    }

    /// Formats the scan result into a clean chat-friendly synthesis for AI conversational display.
    pub fn to_chat_summary(&self) -> String {
        let mut out = String::new();
        out.push_str("### 🛡️ Snatchy Security Scan Audit\n\n");
        out.push_str(&format!(
            "- **Files Scanned**: {}\n- **Dependencies**: {}\n- **Duration**: {}ms\n- **Overall Risk**: `{:?}`\n\n",
            self.files_scanned, self.dependencies_scanned, self.duration_ms, self.risk_level
        ));

        if self.findings.is_empty() && self.vulnerabilities.is_empty() {
            out.push_str("✅ **No malicious code patterns, secrets, or dependency vulnerabilities detected.**\nYour project workspace is clean.\n");
            return out;
        }

        out.push_str(&format!(
            "**Findings Breakdown:**\n- 🔴 Critical: {}\n- 🟠 High: {}\n- 🟡 Medium: {}\n- 🔵 Low: {}\n\n",
            self.summary.critical, self.summary.high, self.summary.medium, self.summary.low
        ));

        for group in &self.grouped_findings {
            out.push_str(&format!("#### {} {} ({})\n", group.icon, group.title, group.findings.len()));
            for f in &group.findings {
                let loc = f.file.as_deref().unwrap_or("general");
                out.push_str(&format!("- `[{:?}]` `{}`: {}\n  *Fix*: {}\n", f.severity, loc, f.description, f.recommendation));
            }
            out.push('\n');
        }

        if !self.vulnerabilities.is_empty() {
            out.push_str("#### 📦 Dependency CVE Vulnerabilities\n");
            for v in self.vulnerabilities.iter().take(8) {
                out.push_str(&format!("- `{}` ({}): range `{}`\n", v.name, v.severity, v.range));
            }
            if self.vulnerabilities.len() > 8 {
                out.push_str(&format!("- ... and {} more dependency vulnerabilities.\n", self.vulnerabilities.len() - 8));
            }
            out.push('\n');
        }

        out
    }
}

pub struct ScanService;

impl ScanService {
    /// Runs a decoupled, complete security and malware audit over the workspace:
    /// 1. Static code analysis (secrets, malware regexes, network probes, obfuscation).
    /// 2. Supply chain analysis.
    /// 3. Dependency CVE check (`npm audit`).
    /// 4. AI False-Positive Reviewer (`LLMSecurityReviewer`).
    /// 5. Aggregation into structured `ScanResult`.
    pub async fn run_scan<F>(
        root: &Path,
        target_dir: &str,
        config: &UnevenConfig,
        mut progress_callback: Option<F>,
    ) -> Result<ScanResult, UnevenError>
    where
        F: FnMut(&str) + Send + Sync,
    {
        let start_time = Instant::now();

        if let Some(ref mut cb) = progress_callback {
            cb("Scanning source code for malicious patterns, secrets and vulnerabilities...");
        }

        // 1. Static analysis (includes Secrets, Malware, Obfuscation, Network, Vulnerabilities)
        let static_findings = pentester::static_analysis(&[target_dir])
            .await
            .unwrap_or_default();

        if let Some(ref mut cb) = progress_callback {
            cb("Auditing supply chain integrity...");
        }

        // 2. Supply chain audit
        let supply_findings = pentester::supply_chain::run_audit(&root.to_string_lossy())
            .await
            .unwrap_or_default();

        if let Some(ref mut cb) = progress_callback {
            cb("Auditing dependency CVEs...");
        }

        // 3. Dependency vulnerability audit
        let (vulnerabilities, audit_skipped, audit_error) = run_npm_audit(root);

        // 4. Combine findings
        let mut all_findings = static_findings;
        all_findings.extend(supply_findings);

        // 5. AI review to minimize false positives
        if let Some(ref mut cb) = progress_callback {
            cb("Reviewing findings with AI to eliminate false positives...");
        }
        let scan_brain = config.get_brain_for_command("scan");
        let reviewer = LLMSecurityReviewer::new(&scan_brain);
        let _ = reviewer.review_findings(&mut all_findings).await;

        let duration_ms = start_time.elapsed().as_millis();
        let files_scanned = count_scanned_files(target_dir);
        let dependencies_scanned = count_dependencies_scanned(root);
        let risk_level = compute_risk_level(&all_findings);
        let summary = count_findings_by_severity(&all_findings);
        let grouped_findings = group_by_category(&all_findings);

        if let Some(ref mut cb) = progress_callback {
            cb("Scan complete.");
        }

        Ok(ScanResult {
            findings: all_findings,
            vulnerabilities,
            audit_skipped,
            audit_error,
            files_scanned,
            dependencies_scanned,
            duration_ms,
            risk_level,
            summary,
            grouped_findings,
        })
    }
}

pub fn run_npm_audit(root: &Path) -> (Vec<DepVulnerability>, bool, Option<String>) {
    let pkg_json = root.join("package.json");
    if !pkg_json.exists() {
        return (vec![], true, None);
    }

    let output = SysCommand::new("npm")
        .args(["audit", "--json"])
        .current_dir(root)
        .output();

    match output {
        Ok(out) => {
            let stdout_str = String::from_utf8_lossy(&out.stdout);
            if let Ok(audit_data) = serde_json::from_str::<NpmAuditOutput>(&stdout_str)
                && let Some(vulns) = audit_data.vulnerabilities
            {
                let list: Vec<DepVulnerability> = vulns
                    .into_iter()
                    .map(|(name, v)| DepVulnerability {
                        name: v.name.unwrap_or(name),
                        severity: v.severity.unwrap_or_else(|| "low".to_string()),
                        is_direct: v.is_direct.unwrap_or(false),
                        range: v.range.unwrap_or_else(|| "*".to_string()),
                        fix_available: v.fix_available.unwrap_or(serde_json::Value::Bool(false)),
                        via: v.via.unwrap_or_default(),
                    })
                    .collect();
                return (list, false, None);
            }
            (
                vec![],
                true,
                Some("Failed to parse npm audit JSON output".to_string()),
            )
        }
        Err(e) => (vec![], true, Some(e.to_string())),
    }
}

pub fn count_scanned_files(dir: &str) -> usize {
    let mut count = 0;
    for entry in walkdir::WalkDir::new(dir).into_iter().flatten() {
        if entry.file_type().is_file()
            && let Some(ext) = entry.path().extension().and_then(|e| e.to_str())
            && ["js", "jsx", "ts", "tsx", "py", "rs", "go", "java", "php", "rb"].contains(&ext)
        {
            count += 1;
        }
    }
    count
}

pub fn count_dependencies_scanned(root: &Path) -> usize {
    if let Ok(content) = fs::read_to_string(root.join("package-lock.json"))
        && let Ok(parsed) = serde_json::from_str::<serde_json::Value>(&content)
        && let Some(packages) = parsed.get("packages").and_then(|p| p.as_object())
    {
        return packages.len().saturating_sub(1);
    }
    0
}

pub fn count_findings_by_severity(findings: &[SecurityFinding]) -> ScanSummary {
    let mut c = ScanSummary::default();
    for f in findings {
        match f.severity {
            Severity::Critical => c.critical += 1,
            Severity::High => c.high += 1,
            Severity::Medium => c.medium += 1,
            Severity::Low => c.low += 1,
            Severity::Info => c.info += 1,
        }
    }
    c
}

pub fn compute_risk_level(findings: &[SecurityFinding]) -> Severity {
    if findings.is_empty() {
        return Severity::Info;
    }
    let mut max_severity = Severity::Info;
    for f in findings {
        if f.severity > max_severity {
            max_severity = f.severity.clone();
        }
    }
    max_severity
}

pub fn group_by_category(findings: &[SecurityFinding]) -> Vec<CategoryGroup> {
    let mut map: HashMap<String, Vec<SecurityFinding>> = HashMap::new();
    for f in findings {
        let cat = get_malware_category(&f.finding_type).to_string();
        map.entry(cat).or_default().push(f.clone());
    }

    let mut result = Vec::new();
    for (category, items) in map {
        let icon = get_category_icon(&category).to_string();
        let title = format_category(&category);
        result.push(CategoryGroup {
            category,
            icon,
            title,
            findings: items,
        });
    }
    result.sort_by(|a, b| a.category.cmp(&b.category));
    result
}

pub fn get_malware_category(finding_type: &str) -> &'static str {
    if finding_type.contains("remote_shell") || finding_type.contains("reverse_shell") {
        "remote-shell"
    } else if finding_type.contains("data_exfiltration") {
        "data-exfiltration"
    } else if finding_type.contains("obfuscated") {
        "obfuscation"
    } else if finding_type.contains("credential") || finding_type.contains("secret") {
        "credential-theft"
    } else if finding_type.contains("persistence") {
        "persistence"
    } else if finding_type.contains("miner") {
        "crypto-mining"
    } else if finding_type.contains("Typosquatting") {
        "typosquatting"
    } else {
        "supply-chain"
    }
}

pub fn get_category_icon(category: &str) -> &'static str {
    match category {
        "remote-shell" => "🐚",
        "data-exfiltration" => "📡",
        "obfuscation" => "🔒",
        "supply-chain" => "📦",
        "credential-theft" => "🔑",
        "persistence" => "⚓",
        "crypto-mining" => "⛏️ ",
        "typosquatting" => "🎭",
        _ => "⚠️",
    }
}

pub fn format_category(cat: &str) -> String {
    cat.split('-')
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect::<Vec<String>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[test]
    fn test_compute_risk_level() {
        let findings = vec![
            SecurityFinding {
                severity: Severity::Low,
                ..Default::default()
            },
            SecurityFinding {
                severity: Severity::Critical,
                ..Default::default()
            },
        ];
        assert_eq!(compute_risk_level(&findings), Severity::Critical);
    }

    #[test]
    fn test_scan_summary_counts() {
        let findings = vec![
            SecurityFinding {
                severity: Severity::Critical,
                ..Default::default()
            },
            SecurityFinding {
                severity: Severity::High,
                ..Default::default()
            },
            SecurityFinding {
                severity: Severity::High,
                ..Default::default()
            },
        ];
        let summary = count_findings_by_severity(&findings);
        assert_eq!(summary.critical, 1);
        assert_eq!(summary.high, 2);
        assert_eq!(summary.medium, 0);
    }

    #[test]
    fn test_group_by_category() {
        let findings = vec![
            SecurityFinding {
                finding_type: "malware:reverse_shell_bash_tcp".to_string(),
                ..Default::default()
            },
            SecurityFinding {
                finding_type: "malware:crypto_miner_detected".to_string(),
                ..Default::default()
            },
        ];
        let grouped = group_by_category(&findings);
        assert_eq!(grouped.len(), 2);
        assert!(grouped.iter().any(|g| g.category == "remote-shell"));
        assert!(grouped.iter().any(|g| g.category == "crypto-mining"));
    }

    #[test]
    fn test_scan_result_markdown_report() {
        let temp = tempdir().unwrap();
        let result = ScanResult {
            findings: vec![SecurityFinding {
                severity: Severity::High,
                finding_type: "secrets:aws_key".to_string(),
                file: Some("src/aws.rs".to_string()),
                description: "Exposed AWS Access Key".to_string(),
                recommendation: "Move to env".to_string(),
                ..Default::default()
            }],
            vulnerabilities: vec![],
            audit_skipped: true,
            audit_error: None,
            files_scanned: 10,
            dependencies_scanned: 50,
            duration_ms: 120,
            risk_level: Severity::High,
            summary: ScanSummary {
                high: 1,
                ..Default::default()
            },
            grouped_findings: vec![],
        };

        let report = result.to_markdown_report(temp.path(), ".");
        assert!(report.contains("Security Audit Report"));
        assert!(report.contains("Exposed AWS Access Key"));
        assert!(report.contains("High"));
    }
}
